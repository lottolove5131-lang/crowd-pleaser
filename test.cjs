const {test}=require('node:test');
const assert=require('node:assert/strict');
const handler=require('./api/plan.js');
const {validate,scoreOf,fallbackStory}=handler.testing;
const valid=()=>({city:'New York',friends:[{name:'Maya',favorites:['Taylor Swift']},{name:'Jun',favorites:['Radiohead']}]});
test('accept two friends',()=>assert.equal(validate(valid()).friends.length,2));
test('reject array body',()=>assert.throws(()=>validate([])));
test('reject missing city',()=>assert.throws(()=>validate({...valid(),city:''})));
test('reject long city',()=>assert.throws(()=>validate({...valid(),city:'x'.repeat(81)})));
test('reject single friend',()=>assert.throws(()=>validate({...valid(),friends:valid().friends.slice(0,1)})));
test('reject six friends',()=>assert.throws(()=>validate({...valid(),friends:Array(6).fill(valid().friends[0])})));
test('reject absent name',()=>{const x=valid();x.friends[0].name='';assert.throws(()=>validate(x));});
test('reject non-text favorite',()=>{const x=valid();x.friends[0].favorites=[42];assert.throws(()=>validate(x));});
test('reject empty favorites',()=>{const x=valid();x.friends[0].favorites=[' '];assert.throws(()=>validate(x));});
test('deduplicate favorites',()=>{const x=valid();x.friends[0].favorites=[' Radiohead ','Radiohead'];assert.equal(validate(x).friends[0].favorites.length,1);});
test('rank score is not probability',()=>assert.equal(scoreOf([{entity_id:'a'},{entity_id:'b'}],'b'),.5));
test('missing rank stays zero',()=>assert.equal(scoreOf([],'x'),0));
test('empty recommendations are honest',()=>assert.match(fallbackStory({dinner:[],music:[],movie:[]}),/No recommendation returned/));
test('GET rejected before external calls',async()=>{let status;let body;await handler({method:'GET'},{status(x){status=x;return this;},json(x){body=x;}});assert.equal(status,405);assert.ok(body.error);});
test('malformed JSON rejected',async()=>{let status;await handler({method:'POST',body:'{'},{status(x){status=x;return this;},json(){}});assert.equal(status,400);});
test('oversize body rejected',async()=>{let status;await handler({method:'POST',body:'x'.repeat(40001)},{status(x){status=x;return this;},json(){}});assert.equal(status,413);});
